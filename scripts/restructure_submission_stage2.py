# ---------------------------------------------------------------- 절 분해
HEAD_RE = re.compile(r"^(#{1,3}) (.+)$")


def split_sections(text: str):
    """(heading_line, body) 목록. 첫 원소의 heading 은 None(프런트매터)."""
    lines = text.splitlines(keepends=True)
    out, head, buf = [], None, []
    for ln in lines:
        if HEAD_RE.match(ln.rstrip("\n")):
            out.append((head, "".join(buf)))
            head, buf = ln.rstrip("\n"), []
        else:
            buf.append(ln)
    out.append((head, "".join(buf)))
    return out


def trim(body: str) -> str:
    """본문 끝의 장 구분선(---)과 잉여 공백을 떼어 낸다."""
    b = body.rstrip("\n")
    while b.endswith("---"):
        b = b[: -3].rstrip("\n")
    return b


