def main() -> int:
    text = SRC.read_text(encoding="utf-8")
    sections = split_sections(text)
    front = sections[0][1]
    by_head = {}
    for head, body in sections[1:]:
        if head in by_head:
            print(f"중복 헤딩: {head}", file=sys.stderr)
            return 2
        by_head[head] = body

    used, out = set(), [trim(front)]
    for new_head, old_head in LAYOUT:
        if new_head == "SEP":
            out.append("---")
            continue
        if old_head is None:
            out.append(new_head)
            continue
        if old_head not in by_head:
            print(f"앵커 소실: {old_head}", file=sys.stderr)
            return 2
        used.add(old_head)
        out.append(new_head + "\n\n" + trim(by_head[old_head]))

    # 구 4장 표제는 본문이 없는 껍데기이므로(내용은 §4.8·§4.9 로 이관) 배치하지 않는다.
    shell = "# 4. 과제 기반 검증 게이트 방법론"
    if by_head.get(shell, "").strip():
        print(f"본문이 있는 절을 버릴 뻔했다: {shell}", file=sys.stderr)
        return 2
    used.add(shell)

    missing = set(by_head) - used
    if missing:
        print("배치되지 않은 절이 있다:\n  " + "\n  ".join(sorted(missing)), file=sys.stderr)
        return 2

    result = remap_refs("\n\n".join(out) + "\n")
    SRC.write_text(result, encoding="utf-8")
    print(f"재배열 완료 — {len(result.splitlines())}행")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
